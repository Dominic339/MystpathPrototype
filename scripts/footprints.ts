// Measures every building model and writes the ground each one covers to
// src/sim/data/footprints.ts, so the town planner keeps streets, fields and neighbours
// clear of what is actually drawn. Run with: npm run footprints
import { writeFileSync } from 'node:fs';
import { LINES } from '../src/sim/data/structures';
import { buildingGeometry, townStyle } from '../src/render/buildings';

const models = new Map<string, string>();
for (const l of LINES) for (const t of l.tiers) models.set(t.model, l.kind);
for (const e of ['stone', 'iron', 'medieval', 'renaissance', 'industrial', 'modern', 'techno-magic']) models.set(`farmstead-${e}`, 'acquisition');
const out: Record<string, number> = {};
const front: Record<string, number> = {};
for (const [model, kind] of models) {
  let r = 0;
  for (let v = 0; v < 4; v++) {
    const g = buildingGeometry(model, kind, townStyle(1, 0), v);
    const a = g.getAttribute('position').array as Float32Array;
    for (let i = 0; i < a.length; i += 3) {
      r = Math.max(r, Math.abs(a[i]), Math.abs(a[i + 2]));
      // The front wall: the furthest forward anything stands at waist height near the middle.
      if (a[i + 1] > 0.9 && a[i + 1] < 1.5 && Math.abs(a[i]) < 1.6) front[model] = Math.max(front[model] ?? 0, a[i + 2]);
    }
  }
  front[model] = Math.round(Math.min(front[model] ?? r * 0.5, r) * 10) / 10;
  out[model] = Math.round(r * 10) / 10;
}
const body = Object.entries(out).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': ${v},`).join('\n');
const fronts = Object.entries(front).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  '${k}': ${v},`).join('\n');
writeFileSync(
  'src/sim/data/footprints.ts',
  `// Generated by scripts/footprints.ts from the building models. Do not edit by hand.\n\n/** The half-width of ground each model covers, in metres. */\nexport const MODEL_RADIUS: Readonly<Record<string, number>> = {\n${body}\n};\n\n/** How far in front of its centre each model's front wall (and door) stands. */\nexport const MODEL_FRONT: Readonly<Record<string, number>> = {\n${fronts}\n};\n`,
);
console.log('measured', models.size, 'models');
